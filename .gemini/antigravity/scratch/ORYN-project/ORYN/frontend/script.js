// Main App Object
const app = {
  init() {
    state.movies = [...MOCK_MOVIES];
    this.setupScrollListener();
    this.navigate('landing');
  },

  navigate(pageId) {
    // Hide all pages
    document.querySelectorAll('.page').forEach(page => {
      page.classList.remove('active');
    });

    // Show target page
    const targetPage = document.getElementById(`page-${pageId}`);
    if (targetPage) {
      targetPage.classList.add('active');
      state.currentPage = pageId;
      window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    // Update nav links
    document.querySelectorAll('.nav-link').forEach(link => {
      link.classList.remove('active');
      if (link.dataset.page === pageId) link.classList.add('active');
    });
    document.querySelectorAll('.mobile-nav-item').forEach(link => {
      link.classList.remove('active');
    });

    // Page specific initialization
    if (pageId === 'dashboard') this.renderDashboard();
    if (pageId === 'discover') this.renderDiscover();
    if (pageId === 'analytics') this.renderAnalytics();
    if (pageId === 'profile') this.renderProfile();

    this.updateNavState();
  },

  updateNavState() {
    const authBtn = document.querySelector('.auth-btn-login');
    const userMenu = document.getElementById('user-menu');
    const navLinks = document.querySelector('.nav-links');

    if (state.user) {
      authBtn.classList.add('hidden');
      userMenu.classList.remove('hidden');
      navLinks.innerHTML = `
        <a href="#" class="nav-link ${state.currentPage === 'dashboard' ? 'active' : ''}" data-page="dashboard" onclick="app.navigate('dashboard')">Home</a>
        <a href="#" class="nav-link ${state.currentPage === 'discover' ? 'active' : ''}" data-page="discover" onclick="app.navigate('discover')">Discover</a>
        <a href="#" class="nav-link" data-page="analytics" onclick="app.navigate('analytics')">Analytics</a>
      `;
    } else {
      authBtn.classList.remove('hidden');
      userMenu.classList.add('hidden');
      navLinks.innerHTML = `
        <a href="#" class="nav-link ${state.currentPage === 'landing' ? 'active' : ''}" data-page="landing" onclick="app.navigate('landing')">About</a>
        <a href="#" class="nav-link ${state.currentPage === 'discover' ? 'active' : ''}" data-page="discover" onclick="app.navigate('discover')">Explore</a>
      `;
    }
  },

  setupScrollListener() {
    const navbar = document.getElementById('navbar');
    window.addEventListener('scroll', () => {
      if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
      } else {
        navbar.classList.remove('scrolled');
      }
    });
  },

  showToast(message) {
    const toast = document.getElementById('toast');
    toast.textContent = message;
    toast.classList.add('show');
    setTimeout(() => {
      toast.classList.remove('show');
    }, 3000);
  },

  // Auth Methods
  fillDemoCredentials() {
    document.getElementById('login-email').value = 'demo@oryn.ai';
    document.getElementById('login-password').value = 'oryndemo2026';
  },

  login() {
    const email = document.getElementById('login-email').value;
    // Mock login
    state.user = { id: 1, name: email.split('@')[0], email: email, genres: [], likedMovies: [] };
    this.navigate('dashboard');
    this.showToast('Welcome back!');
  },

  logout() {
    state.user = null;
    this.navigate('landing');
    this.showToast('Logged out successfully');
  },

  // Onboarding
  startOnboarding() {
    const name = document.getElementById('signup-name').value;
    const email = document.getElementById('signup-email').value;
    state.user = { id: 2, name: name || 'User', email: email, genres: [], likedMovies: [] };
    
    this.onboardingStep = 1;
    this.renderOnboardingStep1();
    this.navigate('onboarding');
  },

  renderOnboardingStep1() {
    const container = document.getElementById('onboarding-genres');
    container.innerHTML = MOCK_GENRES.map(genre => `
      <div class="genre-pill ${state.selectedGenres.includes(genre) ? 'selected' : ''}" 
           onclick="app.toggleGenre('${genre}')">${genre}</div>
    `).join('');
    this.updateOnboardingUI();
  },

  toggleGenre(genre) {
    if (state.selectedGenres.includes(genre)) {
      state.selectedGenres = state.selectedGenres.filter(g => g !== genre);
    } else {
      state.selectedGenres.push(genre);
    }
    this.renderOnboardingStep1();
  },

  renderOnboardingStep2() {
    const container = document.getElementById('onboarding-movies');
    container.innerHTML = state.movies.slice(0, 10).map(m => `
      <div class="movie-card" onclick="app.toggleOnboardingMovie(${m.id})">
        <div class="movie-poster-container" style="${state.selectedMovies.includes(m.id) ? 'border: 2px solid var(--accent); box-shadow: 0 0 15px var(--accent-glow);' : ''}">
          <div class="movie-poster-placeholder" style="background:${m.color}">${m.title}</div>
        </div>
      </div>
    `).join('');
    this.updateOnboardingUI();
  },

  toggleOnboardingMovie(id) {
    if (state.selectedMovies.includes(id)) {
      state.selectedMovies = state.selectedMovies.filter(m => m !== id);
    } else {
      state.selectedMovies.push(id);
    }
    this.renderOnboardingStep2();
  },

  renderOnboardingStep3() {
    const container = document.getElementById('onboarding-ratings');
    if (state.selectedMovies.length === 0) {
      container.innerHTML = '<p class="text-muted">No movies selected to rate.</p>';
      return;
    }
    
    const selectedM = state.movies.filter(m => state.selectedMovies.includes(m.id));
    container.innerHTML = selectedM.map(m => `
      <div style="display: flex; justify-content: space-between; align-items: center; padding: 12px; background: var(--bg-card); margin-bottom: 8px; border-radius: 8px;">
        <span style="font-weight: 500;">${m.title}</span>
        <div style="color: #fbbf24; cursor: pointer; letter-spacing: 4px;">★★★★★</div>
      </div>
    `).join('');
    this.updateOnboardingUI();
  },

  updateOnboardingUI() {
    document.querySelectorAll('.onboarding-step').forEach((el, i) => {
      if (i + 1 === this.onboardingStep) el.classList.add('active');
      else el.classList.remove('active');
    });
    
    document.querySelector('.progress-text').textContent = `0${this.onboardingStep} / 03`;
    document.getElementById('onboarding-progress').style.width = `${(this.onboardingStep / 3) * 100}%`;
    
    const backBtn = document.getElementById('onboarding-back');
    const nextBtn = document.getElementById('onboarding-next');
    
    backBtn.style.visibility = this.onboardingStep > 1 ? 'visible' : 'hidden';
    nextBtn.textContent = this.onboardingStep === 3 ? 'Build My ORYN' : 'Continue';
  },

  onboardingNext() {
    if (this.onboardingStep === 1 && state.selectedGenres.length < 3) {
      this.showToast('Please select at least 3 genres');
      return;
    }
    
    if (this.onboardingStep < 3) {
      this.onboardingStep++;
      if (this.onboardingStep === 2) this.renderOnboardingStep2();
      if (this.onboardingStep === 3) this.renderOnboardingStep3();
      this.updateOnboardingUI();
    } else {
      this.finishOnboarding();
    }
  },

  onboardingBack() {
    if (this.onboardingStep > 1) {
      this.onboardingStep--;
      this.updateOnboardingUI();
    }
  },

  finishOnboarding() {
    state.user.genres = state.selectedGenres;
    state.user.likedMovies = state.selectedMovies;
    this.navigate('loading');
    
    setTimeout(() => {
      document.getElementById('loading-text').textContent = 'Your recommendations are ready.';
      setTimeout(() => {
        this.navigate('dashboard');
      }, 1500);
    }, 2500);
  },

  // Dashboard Rendering
  renderDashboard() {
    if (!state.user) {
      this.navigate('login');
      return;
    }
    
    document.getElementById('dash-greeting').textContent = `Good evening, ${state.user.name}.`;
    
    // Render Hero
    const heroMovie = state.movies[0];
    document.getElementById('dash-featured').innerHTML = `
      <div class="featured-card">
        <div class="featured-poster">
          <div class="movie-poster-placeholder" style="background:${heroMovie.color}; height: 100%; font-size: 2rem;">${heroMovie.title}</div>
        </div>
        <div class="featured-info">
          <div class="ai-confidence">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z"></path></svg>
            AI Confidence: 94%
          </div>
          <h2 class="featured-title">${heroMovie.title}</h2>
          <div class="featured-meta">
            <span>${heroMovie.year}</span>
            <span>•</span>
            <span>${heroMovie.genres.join(', ')}</span>
            <span>•</span>
            <span class="movie-rating">★ ${heroMovie.rating}</span>
          </div>
          <p class="featured-desc">${heroMovie.desc}</p>
          <div style="display: flex; gap: 12px; margin-top: auto;">
            <button class="btn btn-primary" onclick="app.showMovie(${heroMovie.id})">View Details</button>
            <button class="btn btn-secondary">Add to List</button>
          </div>
        </div>
      </div>
    `;

    // Render Sections
    const sections = [
      { title: 'Recommended For You', movies: state.movies.slice(1, 7), reason: 'Based on your profile' },
      { title: 'Because You Liked Sci-Fi', movies: state.movies.filter(m => m.genres.includes('Sci-Fi')).slice(0, 6), reason: 'Similar tone' },
      { title: 'Trending Now', movies: [...state.movies].reverse().slice(0, 6), reason: 'Popular today' }
    ];

    document.getElementById('dash-sections').innerHTML = sections.map(sec => `
      <div class="movie-section">
        <div class="section-header">
          <h3>${sec.title}</h3>
          <a href="#" class="see-all">See All</a>
        </div>
        <div class="horizontal-scroll">
          ${sec.movies.map(m => this.createMovieCardHTML(m, sec.reason)).join('')}
        </div>
      </div>
    `).join('');
  },

  createMovieCardHTML(m, reason = '') {
    return `
      <div class="movie-card" onclick="app.showMovie(${m.id})">
        <div class="movie-poster-container">
          <div class="movie-poster-placeholder" style="background:${m.color}">${m.title}</div>
          <div class="movie-overlay">
            <div class="overlay-top">
              <span class="movie-rating">★ ${m.rating}</span>
            </div>
            <div class="overlay-bottom">
              <button class="btn btn-primary btn-block" style="padding: 6px; font-size: 0.8rem;">View</button>
            </div>
          </div>
        </div>
        <div class="movie-title-sm">${m.title}</div>
        <div class="movie-meta text-muted" style="font-size: 0.8rem;">${m.year}</div>
        ${reason ? `<div class="movie-reason">${reason}</div>` : ''}
      </div>
    `;
  },

  showMovie(id) {
    const movie = state.movies.find(m => m.id === id);
    if (!movie) return;

    const container = document.getElementById('movie-detail-container');
    container.innerHTML = `
      <div class="container">
        <button class="btn btn-secondary mt-4" style="margin-bottom: 24px;" onclick="app.navigate('dashboard')">
          ← Back
        </button>
        <div class="movie-detail-hero">
          <div class="movie-detail-bg" style="background-color: ${movie.color};"></div>
          <div class="movie-detail-content relative">
            <div class="movie-detail-poster">
              <div class="movie-poster-placeholder" style="background:${movie.color}; height: 450px; font-size: 2rem;">${movie.title}</div>
            </div>
            <div class="movie-detail-info">
              <h1 class="movie-detail-title">${movie.title}</h1>
              <div class="movie-detail-meta">
                <span>${movie.year}</span>
                <span>•</span>
                <span>${movie.genres.join(', ')}</span>
                <span>•</span>
                <span class="movie-rating" style="font-size: 1.1rem;">★ ${movie.rating}</span>
              </div>
              <p class="movie-detail-desc">${movie.desc}</p>
              <div class="movie-detail-actions">
                <button class="btn btn-primary btn-lg">Watch Now</button>
                <button class="btn btn-secondary btn-lg">Add to List</button>
              </div>

              <div class="explanation-card">
                <h4><svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><line x1="12" y1="16" x2="12" y2="12"></line><line x1="12" y1="8" x2="12.01" y2="8"></line></svg> Why ORYN Recommends This</h4>
                <ul class="explanation-list">
                  <li>Strong match with your preference for ${movie.genres[0]}</li>
                  <li>Similar narrative structure to movies you rated highly</li>
                  <li>92% of users with your taste profile enjoyed this</li>
                </ul>
              </div>
            </div>
          </div>
        </div>
      </div>
    `;
    this.navigate('movie');
  },

  // Discover Page
  renderDiscover() {
    const genreContainer = document.getElementById('discover-genres');
    genreContainer.innerHTML = MOCK_GENRES.slice(0, 8).map(g => `
      <button class="filter-pill">${g}</button>
    `).join('');

    const grid = document.getElementById('discover-grid');
    grid.innerHTML = state.movies.map(m => this.createMovieCardHTML(m)).join('');
  },

  // Search
  openSearch() {
    document.getElementById('search-modal').classList.add('active');
    setTimeout(() => document.getElementById('search-input').focus(), 100);
    this.handleSearch();
  },

  closeSearch() {
    document.getElementById('search-modal').classList.remove('active');
    document.getElementById('search-input').value = '';
  },

  handleSearch() {
    const q = document.getElementById('search-input').value.toLowerCase();
    const results = state.movies.filter(m => m.title.toLowerCase().includes(q) || m.genres.some(g => g.toLowerCase().includes(q)));
    
    document.getElementById('search-results').innerHTML = results.map(m => `
      <div class="movie-card" onclick="app.closeSearch(); app.showMovie(${m.id})">
        <div class="movie-poster-container">
          <div class="movie-poster-placeholder" style="background:${m.color}">${m.title}</div>
        </div>
        <div class="movie-title-sm">${m.title}</div>
        <div class="movie-meta text-muted" style="font-size: 0.8rem;">${m.year}</div>
      </div>
    `).join('');
  },

  // Profile
  renderProfile() {
    if (!state.user) {
      this.navigate('login');
      return;
    }
    
    document.getElementById('profile-name').textContent = state.user.name;
    document.getElementById('profile-email').textContent = state.user.email;
    document.getElementById('profile-avatar').textContent = state.user.name.charAt(0).toUpperCase();

    document.getElementById('profile-movies').innerHTML = state.movies.slice(0, 4).map(m => this.createMovieCardHTML(m)).join('');
  },

  // Analytics
  renderAnalytics() {
    document.getElementById('analytics-metrics').innerHTML = MOCK_ANALYTICS.metrics.map(m => `
      <div class="metric-card">
        <div class="metric-title">${m.name} (${m.model})</div>
        <div class="metric-val" style="color: ${m.color}">${m.value}</div>
      </div>
    `).join('');

    const chartContainer = document.getElementById('analytics-chart');
    chartContainer.innerHTML = MOCK_ANALYTICS.models.map(m => {
      const height = m.n5 * 100;
      const isOryn = m.name.includes('ORYN');
      return `
        <div class="chart-bar-wrapper">
          <div class="chart-val">${(m.n5).toFixed(2)}</div>
          <div class="chart-bar ${isOryn ? 'oryn' : ''}" style="height: ${height}%;"></div>
          <div class="chart-label">${m.name}</div>
        </div>
      `;
    }).join('');

    // Trigger animation
    setTimeout(() => {
      chartContainer.classList.add('loaded');
    }, 100);
  }
};

// Initialize app on load
document.addEventListener('DOMContentLoaded', () => {
  app.init();
});
